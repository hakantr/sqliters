#!/usr/bin/env python3
"""Translate SQLite 3.54.1 pragma.h for the reference build (no writes to SQLite)."""
import argparse
import pathlib
import re
import subprocess

p = argparse.ArgumentParser(description=__doc__)
p.add_argument("header", type=pathlib.Path)
p.add_argument("output", type=pathlib.Path)
a = p.parse_args()
source = subprocess.check_output(
    ["cc", "-E", "-P", "-x", "c", "-DSQLITE_ENABLE_FTS5",
     "-DSQLITE_ENABLE_RTREE", "-DSQLITE_ENABLE_DBSTAT_VTAB",
     "-DSQLITE_ENABLE_MATH_FUNCTIONS", str(a.header)], text=True)
columns = re.search(r"pragCName\[\]\s*=\s*\{(.*?)\};", source, re.S)[1]
entries = re.search(r"aPragmaName\[\]\s*=\s*\{(.*?)\};", source, re.S)[1]
out = ["// Generated by tools/generate_pragma_table.py from SQLite 3.54.1 pragma.h.",
       "// Reference build: FTS5, RTREE, DBSTAT_VTAB, MATH_FUNCTIONS; Unix, no DEBUG/TEST.",
       "use crate::consts::*;", "use super::PragmaName;", "",
       "pub(super) const COLUMN_NAMES: &[&str] = &[" + columns + "];", "",
       "pub(super) const PRAGMAS: &[PragmaName] = &["]
for body in re.findall(r"\{([^{}]+)\}", entries):
    name, typ, flags, start, count, arg = (s.strip() for s in body.split(","))
    arg = {"BTREE_APPLICATION_ID": "8", "BTREE_DATA_VERSION": "15", "BTREE_FREE_PAGE_COUNT": "0", "BTREE_SCHEMA_VERSION": "1", "BTREE_USER_VERSION": "6"}.get(arg, arg)
    out.append(f"    PragmaName {{ name: {name}, typ: {typ}, flags: {flags}, column: {start}, n_column: {count}, arg: {arg} }},")
out.extend(["];", ""])
a.output.write_text("\n".join(out))
