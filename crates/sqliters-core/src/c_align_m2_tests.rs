//! C-alignment regression tests (step M2: statement lifetime of the port of C's virtual machine). Each test runs an
//! op script — statements prepared into slots and stepped a few rows at a time while other statements run, reset,
//! rebound, interrupted — through the `Connection` API with the machine switched on for the test thread. Every expected
//! line (rows, error code and message, `changes()` / `total_changes()` / `last_insert_rowid()` after each op, progress
//! callback counts, `sqlite3_stmt_status` counters, column names) is what the C library SQLite 3.54.1 prints for the same
//! script (generated by target/perf-work/m2/gen_tests_m2.py with target/perf-work/m2/drv/c/rdrv2). Nothing here depends
//! on files outside the repository.
use std::collections::HashMap;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};

use crate::{Connection, Statement, StepResult};
use sqliters_types::Value;

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len() / 2).map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap()).collect()
}

fn param(s: &str) -> Value {
    let (tag, rest) = s.split_at(1);
    match tag {
        "N" => Value::Null,
        "I" => Value::Integer(rest.parse().unwrap()),
        "T" => Value::Text(String::from_utf8(unhex(rest)).unwrap()),
        _ => panic!("bad param {s}"),
    }
}

fn show(v: &Value) -> String {
    match v {
        Value::Null => "NULL".to_owned(),
        Value::Integer(i) => i.to_string(),
        Value::Real(r) => format!("r{:016x}", r.to_bits()),
        Value::Text(t) => format!("'{t}'"),
        Value::Blob(b) => format!("x'{}'", b.iter().map(|x| format!("{x:02x}")).collect::<String>()),
    }
}

/// The op interpreter of target/perf-work/m2/drv/r/src/main.rs.
fn run(script: &[&str]) -> Vec<String> {
    run_dump(script, "")
}

/// [`run`] with op `D <sql>`: the statement runs C's own program for it (`dump`: the programs C SQLite prepared for
/// the D lines of the script, dumped by target/perf-work/m2/drv/c/rdrv3 — `sqliters_vdbe::progdump`), then is stepped
/// to its end.
fn run_dump(script: &[&str], dump: &str) -> Vec<String> {
    let conn = Connection::open_in_memory().unwrap();
    let _on = crate::vdbe_host::ForceMachine::on();
    let mut out = Vec::new();
    let mut slots: HashMap<usize, Statement> = HashMap::new();
    let n_progress = Arc::new(AtomicU64::new(0));
    for (ln, line) in script.iter().enumerate() {
        let mut parts = line.split('\t');
        let kind = parts.next().unwrap();
        let arg = parts.next().unwrap_or("");
        let mut err: Option<(i32, String)> = None;
        match kind {
            "E" => {
                if let Err(e) = conn.execute_batch(arg) {
                    err = Some((e.extended_code, e.message.clone()));
                }
            }
            "S" => match conn.prepare(arg) {
                Ok(mut st) => loop {
                    match st.step() {
                        Ok(StepResult::Row(r)) => out.push(format!("{ln} row {}", r.values().iter().map(show).collect::<Vec<_>>().join("|"))),
                        Ok(StepResult::Done) => break,
                        Err(e) => {
                            err = Some((e.extended_code, e.message.clone()));
                            break;
                        }
                    }
                },
                Err(e) => err = Some((e.extended_code, e.message.clone())),
            },
            "D" => match conn.prepare(arg) {
                Ok(mut st) => {
                    let prog = sqliters_vdbe::progdump::load(dump, ln as i64).unwrap().expect("program of the D line");
                    st.set_c_program(prog).unwrap();
                    loop {
                        match st.step() {
                            Ok(StepResult::Row(r)) => out.push(format!("{ln} row {}", r.values().iter().map(show).collect::<Vec<_>>().join("|"))),
                            Ok(StepResult::Done) => break,
                            Err(e) => {
                                err = Some((e.extended_code, e.message.clone()));
                                break;
                            }
                        }
                    }
                }
                Err(e) => err = Some((e.extended_code, e.message.clone())),
            },
            "P" => {
                let id: usize = arg.parse().unwrap();
                slots.remove(&id);
                match conn.prepare(parts.next().unwrap()) {
                    Ok(mut st) => {
                        for (i, p) in parts.enumerate() {
                            st.bind(i + 1, param(p)).unwrap();
                        }
                        slots.insert(id, st);
                    }
                    Err(e) => err = Some((e.extended_code, e.message.clone())),
                }
            }
            "N" => {
                let n: usize = parts.next().unwrap().parse().unwrap();
                if let Some(st) = slots.get_mut(&arg.parse().unwrap()) {
                    for _ in 0..n {
                        match st.step() {
                            Ok(StepResult::Row(r)) => out.push(format!("{ln} row {}", r.values().iter().map(show).collect::<Vec<_>>().join("|"))),
                            Ok(StepResult::Done) => {
                                out.push(format!("{ln} done"));
                                let _ = st.reset();
                                break;
                            }
                            Err(e) => {
                                err = Some((e.extended_code, e.message.clone()));
                                let _ = st.reset();
                                break;
                            }
                        }
                    }
                }
            }
            "R" => {
                if let Some(st) = slots.get_mut(&arg.parse().unwrap()) {
                    let _ = st.reset();
                }
            }
            "B" => {
                if let Some(st) = slots.get_mut(&arg.parse().unwrap()) {
                    for (i, p) in parts.enumerate() {
                        st.bind(i + 1, param(p)).unwrap();
                    }
                }
            }
            "C" => {
                if let Some(st) = slots.get_mut(&arg.parse().unwrap()) {
                    let _ = st.clear_bindings();
                }
            }
            "G" => {
                let period: i32 = arg.parse().unwrap();
                let stop: u64 = parts.next().map_or(0, |s| s.parse().unwrap());
                n_progress.store(0, Ordering::SeqCst);
                if period > 0 {
                    let c = Arc::clone(&n_progress);
                    conn.progress_handler(
                        period,
                        Some(Box::new(move || {
                            let n = c.fetch_add(1, Ordering::SeqCst) + 1;
                            stop > 0 && n >= stop
                        })),
                    )
                    .unwrap();
                } else {
                    conn.progress_handler(0, None).unwrap();
                }
            }
            "O" => out.push(format!("{ln} progress {}", n_progress.swap(0, Ordering::SeqCst))),
            "I" => conn.interrupt_handle().interrupt(),
            "V" => {
                if let Some(st) = slots.get_mut(&arg.parse().unwrap()) {
                    let v: Vec<String> = [1usize, 2, 3, 4, 6, 7, 8].iter().map(|&op| st.machine_stmt_status(op, false).to_string()).collect();
                    out.push(format!("{ln} status {}", v.join(" ")));
                }
            }
            "M" => {
                if let Some(st) = slots.get(&arg.parse().unwrap()) {
                    let names = st.column_names();
                    out.push(format!("{ln} cols {}{}{}", names.len(), if names.is_empty() { "" } else { " " }, names.join("|")));
                }
            }
            "X" => {
                slots.remove(&arg.parse().unwrap());
            }
            _ => panic!("bad op {line}"),
        }
        let tail = format!(" | {} {} {}", conn.changes(), conn.total_changes(), conn.last_insert_rowid());
        match err {
            None => out.push(format!("{ln} ok{tail}")),
            Some((code, msg)) => out.push(format!("{ln} err {code} {msg}{tail}")),
        }
    }
    out
}

