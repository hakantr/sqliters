//! `resolve.c`: name resolution. The routines in this file walk the parse tree and resolve
//! all identifiers (TK_ID / TK_DOT) by associating them with a particular table and column,
//! convert function calls into TK_FUNCTION / TK_AGG_FUNCTION, and resolve the terms of
//! ORDER BY and GROUP BY clauses.
//!
//! Not ported in step V1 (the statement is reported as unsupported when one is reached, or
//! the hook is a documented stub): NATURAL / USING joins and nested FROM clauses in
//! `lookupName`, the `new.*` / `old.*` references of triggers (`pParse->pTriggerTab`), the
//! `excluded.*` table of an upsert (`NC_UUpsert`), RETURNING (`NC_UBaseReg`), window
//! functions, and the authorizer callbacks (`sqlite3AuthRead`, `sqlite3AuthCheck`): the
//! engine authorizes the statement itself.

use crate::callback::*;
use crate::consts::*;
use crate::expr::*;
use crate::select::*;
use crate::sqliteint::*;
use crate::tk::*;
use crate::util::*;
use crate::walker::*;

/// `incrAggFunctionDepth(pExpr, N)`: walk the expression tree and increment the
/// aggregate function depth (the Expr.op2 field) by N on every TK_AGG_FUNCTION node.
fn incr_agg_function_depth(p: &mut Parse, e: ExprId, n: i32) {
    if n > 0 {
        fn incr_agg_depth(p: &mut Parse, w: &mut Walker, e: ExprId) -> i32 {
            if p.e(e).op == TK_AGG_FUNCTION {
                p.em(e).op2 = (p.e(e).op2 as i32 + w.n) as u8;
            }
            WRC_Continue
        }
        let mut w = Walker { x_expr_callback: Some(incr_agg_depth), n, ..Walker::default() };
        sqlite3_walk_expr(p, &mut w, e);
    }
}

/// `resolveAlias(pParse, pEList, iCol, pExpr, nSubquery)`: turn the `e` expression into an
/// alias for the `i_col`-th column of the result set in `e_list`. The contents of the node
/// `e` are replaced by a copy of the result-set expression (C swaps the node contents so
/// that pointers to `e` stay valid).
fn resolve_alias(p: &mut Parse, e_list: ExprListId, i_col: i32, e: ExprId, n_subquery: i32) {
    let orig = p.l(e_list).a[i_col as usize].p_expr;
    if p.e(e).p_agg_info.nn() {
        return;
    }
    let mut dup = sqlite3_expr_dup(p, orig, 0);
    incr_agg_function_depth(p, dup, n_subquery);
    if p.e(e).op == TK_COLLATE {
        let z = p.e(e).tok().to_owned();
        dup = sqlite3_expr_add_collate_string(p, dup, &z);
    }
    // memcpy(&temp, pDup, sizeof(Expr)); memcpy(pDup, pExpr, sizeof(Expr)); memcpy(pExpr, &temp, ...)
    p.a_expr.swap(dup.ix(), e.ix());
    if p.e(e).has(EP_WinFunc) {
        let wn = p.e(e).y_win;
        if wn.nn() {
            p.a_win[wn.ix()].p_owner = e;
        }
    }
}

/// `areDoubleQuotedStringsEnabled(db, pTopNC)`: return TRUE if the double-quoted string
/// mis-feature should be supported.
fn are_double_quoted_strings_enabled(p: &Parse, top_nc: NcId) -> bool {
    if p.db.init_busy {
        return true; // Always support for legacy schemas
    }
    if p.nc(top_nc).nc_flags & NC_IsDDL != 0 {
        // Currently parsing a DDL statement
        // (sqlite3WritableSchema(db) && DqsDML: writable_schema is not modelled; CREATE
        // statements are not generated by step V1)
        (p.db.flags & SQLITE_DqsDDL) != 0
    } else {
        // Currently parsing a DML statement
        (p.db.flags & SQLITE_DqsDML) != 0
    }
}

/// `sqlite3ColumnIndex(pTab, zCol)`: the index of the column named `z_col` in table `tab`,
/// or -1 if there is no such column.
pub fn sqlite3_column_index(p: &Parse, tab: TableId, z_col: &str) -> i32 {
    for (i, c) in p.tab(tab).a_col.iter().enumerate() {
        if c.z_cn_name.eq_ignore_ascii_case(z_col) {
            return i as i32;
        }
    }
    -1
}

/// `VisibleRowid(pTab)`
fn visible_rowid(p: &Parse, tab: TableId) -> bool {
    (p.tab(tab).tab_flags & TF_NoVisibleRowid) == 0
}

/// `sqlite3MatchEName(pItem, zCol, zTab, zDb, pbRowid)`: subqueries store the original
/// database, table and column names for their result sets in ExprList.a[].zEName, in the
/// form "DATABASE.TABLE.COLUMN", and mark the expression-list item by setting
/// ExprList.a[].fg.eEName to ENAME_TAB or ENAME_ROWID. This routine returns non-zero if
/// zEName matches zDb, zTab, and zCol. If any of zDb, zTab, and zCol are NULL then those
/// fields will match anything.
pub fn sqlite3_match_e_name(
    p: &Parse,
    list: ExprListId,
    j: usize,
    z_col: Option<&str>,
    z_tab: Option<&str>,
    z_db: Option<&str>,
    pb_rowid: Option<&mut bool>,
) -> bool {
    let item = &p.l(list).a[j];
    let e_e_name = item.e_e_name as i32;
    if e_e_name != ENAME_TAB && (e_e_name != ENAME_ROWID || pb_rowid.is_none()) {
        return false;
    }
    let z_span = item.z_e_name.as_deref().unwrap_or("");
    let mut parts = z_span.splitn(3, '.');
    let (s_db, s_tab, s_col) = (parts.next().unwrap_or(""), parts.next().unwrap_or(""), parts.next().unwrap_or(""));
    if let Some(d) = z_db
        && !s_db.eq_ignore_ascii_case(d)
    {
        return false;
    }
    if let Some(t) = z_tab
        && !s_tab.eq_ignore_ascii_case(t)
    {
        return false;
    }
    if let Some(c) = z_col {
        if e_e_name == ENAME_TAB && !s_col.eq_ignore_ascii_case(c) {
            return false;
        }
        if e_e_name == ENAME_ROWID && !sqlite3_is_rowid(c) {
            return false;
        }
    }
    if e_e_name == ENAME_ROWID
        && let Some(b) = pb_rowid
    {
        *b = true;
    }
    true
}

/// `sqlite3ExprColUsed(pExpr)`: return the Bitmask of columns used by a TK_COLUMN expression
/// node: the bit of the column, or every column of the table if the column is generated.
pub fn sqlite3_expr_col_used(p: &Parse, e: ExprId) -> Bitmask {
    let mut n = p.e(e).i_column as i32;
    let t = p.tab(p.e(e).y_tab);
    if (t.tab_flags & TF_HasGenerated) != 0 && (t.a_col[n as usize].col_flags & COLFLAG_GENERATED as u16) != 0 {
        if t.n_col() as i32 >= BMS { u64::MAX } else { (1u64 << t.n_col()) - 1 }
    } else {
        if n >= BMS {
            n = BMS - 1;
        }
        1u64 << n
    }
}

/// `extendFJMatch(pParse, ppList, pMatch, iColumn)`: create a new expression term for the
/// column specified by pMatch and iColumn. Append this new expression term to the FULL JOIN
/// Match set in *ppList. Create a new *ppList if this is the first term in the set.
fn extend_fj_match(p: &mut Parse, list: &mut ExprListId, m: (SrcListId, usize), i_column: i16) {
    let new = sqlite3_expr_alloc(p, TK_COLUMN, None, 0);
    let (i_cursor, tab) = {
        let it = &p.src(m.0).a[m.1];
        (it.i_cursor, it.p_s_tab)
    };
    let x = p.em(new);
    x.i_table = i_cursor;
    x.i_column = i_column;
    x.y_tab = tab;
    x.flags |= EP_CanBeNull;
    *list = sqlite3_expr_list_append(p, *list, new);
}

/// `isValidSchemaTableName(zTab, pTab, zDb)`: return TRUE (non-zero) if zTab is a valid name
/// for the schema table pTab.
fn is_valid_schema_table_name(z_tab: &str, z_legacy: &str, has_db: bool) -> bool {
    if z_tab.len() < 7 || !z_tab.as_bytes()[..7].eq_ignore_ascii_case(b"sqlite_") {
        return false;
    }
    let tail = &z_tab[7..];
    if z_legacy.len() >= 7 && &z_legacy[7..] == "temp_master" {
        if tail.eq_ignore_ascii_case("temp_schema") {
            return true;
        }
        if !has_db {
            return false;
        }
        if tail.eq_ignore_ascii_case("master") {
            return true;
        }
        if tail.eq_ignore_ascii_case("schema") {
            return true;
        }
    } else if tail.eq_ignore_ascii_case("schema") {
        return true;
    }
    false
}

/// `sqlite3CreateColumnExpr(db, pSrc, iSrc, iCol)`: allocate and return a pointer to an
/// expression to load the column iCol from datasource iSrc in SrcList pSrc.
pub fn sqlite3_create_column_expr(p: &mut Parse, src: SrcListId, i_src: usize, i_col: i32) -> ExprId {
    let e = sqlite3_expr_alloc(p, TK_COLUMN, None, 0);
    let (tab, i_cursor) = {
        let it = &p.src(src).a[i_src];
        (it.p_s_tab, it.i_cursor)
    };
    p.em(e).y_tab = tab;
    p.em(e).i_table = i_cursor;
    if p.tab(tab).i_p_key as i32 == i_col {
        p.em(e).i_column = -1;
    } else {
        p.em(e).i_column = i_col as i16;
        let t = p.tab(tab);
        if (t.tab_flags & TF_HasGenerated) != 0 && (t.a_col[i_col as usize].col_flags & COLFLAG_GENERATED as u16) != 0 {
            let m = if t.n_col() >= 64 { u64::MAX } else { (1u64 << t.n_col()) - 1 };
            p.srcm(src).a[i_src].col_used = m;
        } else {
            p.srcm(src).a[i_src].col_used |= 1u64 << (if i_col >= BMS { BMS - 1 } else { i_col });
        }
    }
    e
}

/// `lookupName(pParse, zDb, zTab, pRight, pNC, pExpr)`: given the name of a column of the
/// form X.Y.Z or Y.Z or just Z, look up that name in the set of source tables in `nc` and
/// its parents. On success `e` becomes a TK_COLUMN (or the result-set expression it is an
/// alias for). If the name cannot be resolved unambiguously, leave an error message in the
/// Parse and return WRC_Abort. Return WRC_Prune on success.
fn lookup_name(p: &mut Parse, z_db: Option<String>, z_tab: Option<String>, right: ExprId, nc: NcId, e: ExprId) -> i32 {
    let mut cnt = 0; // Number of matching column names
    let mut cnt_tab = 0; // Number of potential "rowid" matches
    let mut n_subquery = 0; // How many levels of subquery
    let mut p_match: Option<(SrcListId, usize)> = None; // The matching pSrcList item
    let top_nc = nc; // First namecontext in the list
    let mut nc = nc;
    let mut e_new_expr_op = TK_COLUMN;
    let z_col = p.e(right).tok().to_owned();
    let mut z_db = z_db;

    // Initialize the node to no-match
    p.em(e).i_table = -1;

    // Translate the schema name in zDb into a pointer to the corresponding schema. If not
    // found, pSchema will remain NULL and nothing will match resulting in an appropriate error
    // message toward the end of this routine.
    let mut schema: Option<i32> = None;
    if let Some(zdb) = z_db.clone() {
        if (p.nc(nc).nc_flags & (NC_PartIdx | NC_IsCheck)) != 0 {
            // Silently ignore database qualifiers inside CHECK constraints and partial
            // indices. Do not raise errors because that might break legacy and because it
            // does not hurt anything to just ignore the database name.
            z_db = None;
        } else {
            let mut i = 0;
            while i < p.db.a_db.len() {
                if p.db.a_db[i].z_db_s_name.eq_ignore_ascii_case(&zdb) {
                    schema = Some(i as i32);
                    break;
                }
                i += 1;
            }
            if i == p.db.a_db.len() && "main".eq_ignore_ascii_case(&zdb) {
                // This branch is taken when the main database has been renamed using
                // SQLITE_DBCONFIG_MAINDBNAME.
                schema = Some(0);
                z_db = Some(p.db.a_db[0].z_db_s_name.clone());
            }
        }
    }

    // Start at the inner-most context and move outward until a match is found
    let mut found_alias = false;
    let mut fj_match = ExprListId::NULL; // Matches for FULL JOIN .. USING
    loop {
        let src_list = p.nc(nc).p_src_list;
        if src_list.nn() {
            for i in 0..p.src(src_list).a.len() {
                let (tab, is_nested_from, is_using, p_using, jointype, z_alias) = {
                    let it = &p.src(src_list).a[i];
                    (it.p_s_tab, it.is_nested_from, it.is_using, it.p_using, it.jointype as i32, it.z_alias.clone())
                };
                if is_nested_from {
                    // In this case, pItem is a subquery that has been formed from a
                    // parenthesized subset of the FROM clause terms. Example:
                    //   .... FROM t1 LEFT JOIN (t2 RIGHT JOIN t3 USING(x)) USING(y) ...
                    //                          \_________________________/
                    //             This pItem -------------^
                    let mut hit = false;
                    let sel = p.src(src_list).a[i].p_subq.as_ref().expect("subquery").p_select;
                    let e_list = p.s(sel).p_e_list;
                    for j in 0..p.l(e_list).a.len() {
                        let mut b_rowid = false; // True if possible rowid match
                        if !sqlite3_match_e_name(p, e_list, j, Some(&z_col), z_tab.as_deref(), z_db.as_deref(), Some(&mut b_rowid)) {
                            continue;
                        }
                        if !b_rowid {
                            if cnt > 0 {
                                if !is_using
                                    || crate::build::sqlite3_id_list_index(p, p_using, &z_col) < 0
                                    || p_match == Some((src_list, i))
                                {
                                    // Two or more tables have the same column name which is
                                    // not joined by USING. Or, a single table has two columns
                                    // that match a USING term (if pMatch==pItem). These are
                                    // both "ambiguous column name" errors. Signal as much by
                                    // clearing pFJMatch and letting cnt go above 1.
                                    fj_match = ExprListId::NULL;
                                } else if (jointype & JT_RIGHT) == 0 {
                                    // An INNER or LEFT JOIN. Use the left-most table
                                    continue;
                                } else if (jointype & JT_LEFT) == 0 {
                                    // A RIGHT JOIN. Use the right-most table
                                    cnt = 0;
                                    fj_match = ExprListId::NULL;
                                } else {
                                    // For a FULL JOIN, we must construct a coalesce() func
                                    let ic = p.e(e).i_column;
                                    extend_fj_match(p, &mut fj_match, p_match.expect("match"), ic);
                                }
                            }
                            cnt += 1;
                            hit = true;
                        } else if cnt > 0 {
                            // This is a potential rowid match, but there has already been a
                            // real match found. So this can be ignored.
                            continue;
                        }
                        cnt_tab += 1;
                        p_match = Some((src_list, i));
                        p.em(e).i_column = j as i16;
                        p.lm(e_list).a[j].b_used = true;
                        // rowid cannot be part of a USING clause - assert() this.
                        if p.l(e_list).a[j].b_using_term {
                            break;
                        }
                    }
                    if hit || z_tab.is_none() {
                        continue;
                    }
                }
                if let Some(ztab) = z_tab.as_deref() {
                    if z_db.is_some() {
                        let tdb = p.tab(tab).i_db;
                        if (if tdb < 0 { None } else { Some(tdb) }) != schema {
                            continue;
                        }
                        if schema.is_none() && z_db.as_deref() != Some("*") {
                            continue;
                        }
                    }
                    if let Some(alias) = z_alias.as_deref() {
                        if !ztab.eq_ignore_ascii_case(alias) {
                            continue;
                        }
                    } else if !ztab.eq_ignore_ascii_case(&p.tab(tab).z_name) {
                        if p.tab(tab).tnum != 1 {
                            continue;
                        }
                        if !is_valid_schema_table_name(ztab, &p.tab(tab).z_name, z_db.is_some()) {
                            continue;
                        }
                    }
                }
                let j = sqlite3_column_index(p, tab, &z_col);
                if j >= 0 {
                    if cnt > 0 {
                        if !is_using || crate::build::sqlite3_id_list_index(p, p_using, &z_col) < 0 {
                            // Two or more tables have the same column name which is not
                            // joined by USING. This is an error. Signal as much by clearing
                            // pFJMatch and letting cnt go above 1.
                            fj_match = ExprListId::NULL;
                        } else if (jointype & JT_RIGHT) == 0 {
                            // An INNER or LEFT JOIN. Use the left-most table
                            continue;
                        } else if (jointype & JT_LEFT) == 0 {
                            // A RIGHT JOIN. Use the right-most table
                            cnt = 0;
                            fj_match = ExprListId::NULL;
                        } else {
                            // For a FULL JOIN, we must construct a coalesce() func
                            let ic = p.e(e).i_column;
                            extend_fj_match(p, &mut fj_match, p_match.expect("match"), ic);
                        }
                    }
                    cnt += 1;
                    p_match = Some((src_list, i));
                    // Substitute the rowid (column -1) for the INTEGER PRIMARY KEY
                    p.em(e).i_column = if j == p.tab(tab).i_p_key as i32 { -1 } else { j as i16 };
                    if is_nested_from {
                        crate::select::sqlite3_src_item_column_used(p, src_list, i, j);
                    }
                }
                if cnt == 0 && visible_rowid(p, tab) {
                    // pTab is a potential ROWID match. Keep track of it and match the ROWID
                    // later if that seems appropriate. (Search for "cntTab" to find related
                    // code.) Only allow a ROWID match if there is a single ROWID match
                    // candidate.
                    cnt_tab += 1;
                    p_match = Some((src_list, i));
                }
            }
            if let Some((sl, i)) = p_match {
                let (i_cursor, tab, jointype) = {
                    let it = &p.src(sl).a[i];
                    (it.i_cursor, it.p_s_tab, it.jointype)
                };
                let x = p.em(e);
                x.i_table = i_cursor;
                x.y_tab = tab;
                if (jointype as i32 & (JT_LEFT | JT_LTORJ)) != 0 {
                    x.flags |= EP_CanBeNull;
                }
                let tdb = p.tab(tab).i_db;
                schema = if tdb < 0 { None } else { Some(tdb) };
            }
        } // if( pSrcList )

        // If we have not already resolved the name, then maybe it is a new.* or old.*
        // trigger argument reference, or maybe it is an excluded.* from an upsert, or maybe
        // it is a reference to the system RETURNING clause.
        //
        // TODO(later steps): pParse->pTriggerTab (new / old), NC_UUpsert (excluded),
        // NC_UBaseReg (RETURNING). None of these contexts exists in step V1.

        // Perhaps the name is a reference to the ROWID
        if cnt == 0
            && cnt_tab >= 1
            && p_match.is_some()
            && (p.nc(nc).nc_flags & (NC_IdxExpr | NC_GenCol)) == 0
            && sqlite3_is_rowid(&z_col)
        {
            cnt = cnt_tab;
            let (sl, i) = p_match.expect("match");
            let nested = p.src(sl).a[i].is_nested_from;
            let x = p.em(e);
            if !nested {
                x.i_column = -1;
            }
            x.aff_expr = SQLITE_AFF_INTEGER;
        }

        // If the input is of the form Z (not Y.Z or X.Y.Z) then the name Z might refer to a
        // result-set alias. This happens, for example, when we are resolving names in the
        // WHERE clause of the following command:
        //
        //     SELECT a+b AS x FROM table WHERE x<10;
        //
        // In cases like this, replace pExpr with a copy of the expression that forms the
        // result set entry ("a+b" in the example) and return immediately. Note that the
        // expression in the result set should have already been resolved by the time the
        // WHERE clause is resolved.
        //
        // The ability to use an output result-set column in the WHERE, GROUP BY, or HAVING
        // clauses, or as part of a larger expression in the ORDER BY clause is not
        // standard SQL. This is a (goofy) SQLite extension, that is permitted for
        // backwards compatibility only. Hence, we restrict this feature to names that
        // contain no "." operators and for which the name is not found by an ordinary
        // column lookup.
        if cnt == 0 && (p.nc(nc).nc_flags & NC_UEList) != 0 && z_tab.is_none() {
            let e_list = p.nc(nc).p_e_list;
            for j in 0..p.l(e_list).a.len() {
                let (is_name, z_as) = {
                    let it = &p.l(e_list).a[j];
                    (it.e_e_name == ENAME_NAME as u8, it.z_e_name.clone())
                };
                if is_name && z_as.as_deref().is_some_and(|z| z.eq_ignore_ascii_case(&z_col)) {
                    let z_as = z_as.unwrap_or_default();
                    let orig = p.l(e_list).a[j].p_expr;
                    if (p.nc(nc).nc_flags & NC_AllowAgg) == 0 && p.e(orig).has(EP_Agg) {
                        p.error_msg(format!("misuse of aliased aggregate {z_as}"));
                        return WRC_Abort;
                    }
                    if p.e(orig).has(EP_Win) && ((p.nc(nc).nc_flags & NC_AllowWin) == 0 || nc != top_nc) {
                        p.error_msg(format!("misuse of aliased window function {z_as}"));
                        return WRC_Abort;
                    }
                    if sqlite3_expr_vector_size(p, orig) != 1 {
                        p.error_msg("row value misused");
                        return WRC_Abort;
                    }
                    resolve_alias(p, e_list, j as i32, e, n_subquery);
                    cnt = 1;
                    p_match = None;
                    found_alias = true;
                    break;
                }
            }
            if found_alias {
                break;
            }
        }

        // Advance to the next name context. The loop will exit when either we have a match
        // (cnt>0) or when we run out of name contexts.
        if cnt != 0 {
            break;
        }
        nc = p.nc(nc).p_next;
        n_subquery += 1;
        if nc.is_null() {
            break;
        }
    }

    if !found_alias {
        // If X and Y are NULL (in other words if only the column name Z is supplied) and the
        // value of Z is enclosed in double-quotes, then Z is a string literal if it doesn't
        // match any column names. In that case, we need to return right away and not make
        // any changes to pExpr.
        //
        // Because no reference was made to outer contexts, the pNC->nRef fields are not
        // changed in any context.
        if cnt == 0 && z_tab.is_none() {
            if p.e(e).has(EP_DblQuoted) && are_double_quoted_strings_enabled(p, top_nc) {
                // If a double-quoted identifier does not match any known column name, then
                // treat it as a string.
                //
                // This hack was added in the early days of SQLite in a misguided attempt to
                // be compatible with MySQL 3.x, which used double-quotes for strings. I now
                // sorely regret putting in this hack. The effect of this hack is that
                // misspelled identifier names are silently converted into string literals
                // when they ought to be throwing errors.
                let x = p.em(e);
                x.op = TK_STRING;
                x.y_tab = TableId::NULL;
                x.y_win = WindowId::NULL;
                x.y_n_reg = 0;
                x.y_sub_i_addr = 0;
                x.y_sub_reg_return = 0;
                return WRC_Prune;
            }
            if sqlite3_expr_id_to_true_false(p, e) {
                return WRC_Prune;
            }
        }

        // cnt==0 means there was not match.
        // cnt>1 means there were two or more matches.
        //
        // cnt==0 is always an error. cnt>1 is often an error, but might be multiple matches
        // for a NATURAL LEFT JOIN or a LEFT JOIN USING (not ported: reported as unsupported
        // above).
        let mut coalesced = false;
        if cnt != 1 && fj_match.nn() {
            if p.l(fj_match).n_expr() == cnt - 1 {
                {
                    let x = p.em(e);
                    if x.has(EP_Leaf) {
                        x.flags &= !EP_Leaf;
                    } else {
                        x.p_left = ExprId::NULL;
                        x.p_right = ExprId::NULL;
                    }
                }
                let ic = p.e(e).i_column;
                extend_fj_match(p, &mut fj_match, p_match.expect("match"), ic);
                let x = p.em(e);
                x.op = TK_FUNCTION;
                x.z_token = Some("coalesce".to_owned());
                x.x = fj_match.0;
                x.aff_expr = SQLITE_AFF_DEFER;
                cnt = 1;
                coalesced = true;
            } else {
                fj_match = ExprListId::NULL;
            }
        }
        if !coalesced {
        if cnt != 1 {
            let z_err = if cnt == 0 { "no such column" } else { "ambiguous column name" };
            let msg = if let Some(zdb) = z_db.as_deref() {
                format!("{}: {}.{}.{}", z_err, zdb, z_tab.as_deref().unwrap_or(""), z_col)
            } else if let Some(ztab) = z_tab.as_deref() {
                format!("{z_err}: {ztab}.{z_col}")
            } else if cnt == 0 && p.e(right).has(EP_DblQuoted) {
                format!("{z_err}: \"{z_col}\" - should this be a string literal in single-quotes?")
            } else {
                format!("{z_err}: {z_col}")
            };
            p.error_msg(msg);
            p.record_error_offset_of_expr(e);
            p.check_schema = true;
            p.ncm(top_nc).n_nc_err += 1;
            e_new_expr_op = TK_NULL;
        }

        // Remove all substructure from pExpr
        if !p.e(e).has(EP_TokenOnly | EP_Leaf) {
            let x = p.em(e);
            x.p_left = ExprId::NULL;
            x.p_right = ExprId::NULL;
            x.flags |= EP_Leaf;
        }

        // If a column from a table in pSrcList is referenced, then record this fact in the
        // pSrcList.a[].colUsed bitmask. Column 0 causes bit 0 to be set. Column 1 sets bit
        // 1, and so forth. Bit 63 is set if the column number is greater than 62.
        //
        // If any of the columns in the table are generated, set all column-used bits.
        if let Some((sl, i)) = p_match {
            let i_column = p.e(e).i_column;
            if i_column >= 0 {
                let m = sqlite3_expr_col_used(p, e);
                p.srcm(sl).a[i].col_used |= m;
            } else {
                p.srcm(sl).a[i].rowid_used = true;
            }
        }
        p.em(e).op = e_new_expr_op;
        }
    }

    // lookupname_end:
    let _ = (schema, fj_match);
    if cnt == 1 {
        // (sqlite3AuthRead: authorization is done by the engine)
        // Increment the nRef value on all name contexts from TopNC up to the point where the
        // name matched.
        let mut t = top_nc;
        loop {
            p.ncm(t).n_ref += 1;
            if t == nc {
                break;
            }
            t = p.nc(t).p_next;
            if t.is_null() {
                break;
            }
        }
        WRC_Prune
    } else {
        WRC_Abort
    }
}

/// `notValidImpl(pParse, pNC, zMsg, pExpr, pError)`: report an error that an expression is
/// not valid for some set of pNC->ncFlags values.
fn not_valid_impl(p: &mut Parse, nc: NcId, z_msg: &str, e: ExprId, error: ExprId) {
    let f = p.nc(nc).nc_flags;
    let z_in = if f & NC_IdxExpr != 0 {
        "index expressions"
    } else if f & NC_IsCheck != 0 {
        "CHECK constraints"
    } else if f & NC_GenCol != 0 {
        "generated columns"
    } else {
        "partial index WHERE clauses"
    };
    p.error_msg(format!("{z_msg} prohibited in {z_in}"));
    if e.nn() {
        p.em(e).op = TK_NULL;
    }
    p.record_error_offset_of_expr(error);
}

/// `sqlite3ResolveNotValid(P,N,M,X,E,R)`
fn sqlite3_resolve_not_valid(p: &mut Parse, nc: NcId, z_msg: &str, x: i32, e: ExprId, r: ExprId) {
    if (p.nc(nc).nc_flags & x) != 0 {
        not_valid_impl(p, nc, z_msg, e, r);
    }
}

/// `exprProbability(p)`: expression `e` should encode a floating point value between 1.0 and
/// 0.0. Return 134217728 (2^27) times this value, or -1 if the input is not valid.
fn expr_probability(p: &Parse, e: ExprId) -> i32 {
    if p.e(e).op != TK_FLOAT {
        return -1;
    }
    let (r, rc) = sqliters_types::fp::sqlite_atof(p.e(e).tok().as_bytes());
    // (C leaves r at -1.0 when sqlite3AtoF() does not find a number)
    let r = if rc == 0 { -1.0 } else { r };
    if r > 1.0 {
        return -1;
    }
    (r * 134217728.0) as i32
}

/// `resolveSetExprSubtypeArg(pList)`: mark each argument (and what it is a transparent
/// wrapper for) as an argument of a function that reads subtypes.
fn resolve_set_expr_subtype_arg(p: &mut Parse, list: ExprListId) {
    let nn = if list.nn() { p.l(list).a.len() } else { 0 };
    for ii in 0..nn {
        let mut e = p.l(list).a[ii].p_expr;
        loop {
            p.em(e).flags |= EP_SubtArg;
            if p.e(e).op == TK_SELECT {
                let el = p.s(p.e(e).x_select()).p_e_list;
                resolve_set_expr_subtype_arg(p, el);
                break;
            }
            if p.e(e).op == TK_UPLUS {
                e = p.e(e).p_left;
            } else {
                break;
            }
        }
    }
}

/// `resolveExprStep(pWalker, pExpr)`: this routine is a callback for sqlite3WalkExpr().
///
/// Resolve symbolic names into TK_COLUMN operators for the current node in the expression
/// tree. Return 0 to continue the search down the tree or 2 to abort the tree walk.
///
/// This routine also does error checking and name resolution for function names. The
/// operator for aggregate functions is changed to TK_AGG_FUNCTION.
fn resolve_expr_step(p: &mut Parse, w: &mut Walker, e: ExprId) -> i32 {
    let nc = w.p_nc;
    let op = p.e(e).op;
    let mut comparison = false;
    match op {
        // The special operator TK_ROW means use the rowid for the first column in the FROM
        // clause. This is used by the LIMIT and ORDER BY clause handling of UPDATE and
        // DELETE statements (SQLITE_ENABLE_UPDATE_DELETE_LIMIT, not compiled in).
        TK_NOTNULL | TK_ISNULL => {
            // Record the number of outer-context references so that the counts can be
            // restored if the term is optimized away.
            let mut an_ref = [0i32; 8];
            let mut x = nc;
            let mut i = 0;
            while x.nn() && i < an_ref.len() {
                an_ref[i] = p.nc(x).n_ref;
                x = p.nc(x).p_next;
                i += 1;
            }
            let left = p.e(e).p_left;
            sqlite3_walk_expr(p, w, left);
            if sqlite3_expr_can_be_null(p, p.e(e).p_left) {
                // The left-hand side of the IS NULL or IS NOT NULL operator can be NULL, so
                // the operator is not optimized away.
                return WRC_Prune;
            }
            let mut x = nc;
            while x.nn() {
                if (p.nc(x).nc_flags & NC_Where) == 0 {
                    return WRC_Prune; // Not in a WHERE clause. Unsafe to optimize.
                }
                x = p.nc(x).p_next;
            }
            let v = (p.e(e).op == TK_NOTNULL) as i32;
            {
                let n = p.em(e);
                n.i_value = v;
                n.z_token = None;
                n.flags |= EP_IntValue;
                n.op = TK_INTEGER;
            }
            let mut x = nc;
            let mut i = 0;
            while x.nn() && i < an_ref.len() {
                p.ncm(x).n_ref = an_ref[i];
                x = p.nc(x).p_next;
                i += 1;
            }
            p.em(e).p_left = ExprId::NULL;
            return WRC_Prune;
        }

        // A column name:                    ID
        // Or table name and column name:    ID.ID
        // Or a database, table and column:  ID.ID.ID
        //
        // The TK_ID and TK_OUT cases are combined so that there will only be one call to
        // lookupName(). Then the compiler will in-line lookupName() for a size reduction and
        // performance increase.
        TK_ID | TK_DOT => {
            let (z_db, z_table, right);
            if op == TK_ID {
                z_db = None;
                z_table = None;
                right = e;
            } else {
                let mut left = p.e(e).p_left;
                sqlite3_resolve_not_valid(p, nc, "the \".\" operator", NC_IdxExpr | NC_GenCol, ExprId::NULL, e);
                let mut r = p.e(e).p_right;
                if p.e(r).op == TK_ID {
                    z_db = None;
                } else {
                    z_db = Some(p.e(left).tok().to_owned());
                    left = p.e(r).p_left;
                    r = p.e(r).p_right;
                }
                z_table = Some(p.e(left).tok().to_owned());
                right = r;
            }
            return lookup_name(p, z_db, z_table, right, nc, e);
        }

        // Resolve function names
        TK_FUNCTION => {
            let list = p.e(e).x_list();
            let n = if list.nn() { p.l(list).n_expr() } else { 0 };
            let mut no_such_func = 0; // True if no such function exists
            let mut wrong_num_args = false; // True if wrong number of arguments
            let mut is_agg = false; // True if is an aggregate function
            let saved_allow_flags = p.nc(nc).nc_flags & (NC_AllowAgg | NC_AllowWin);
            let z_id = p.e(e).tok().to_owned();
            let mut def = sqlite3_find_function(p, &z_id, n, 0);
            match def.clone() {
                None => {
                    def = sqlite3_find_function(p, &z_id, -2, 0);
                    if def.is_none() {
                        no_such_func = 1;
                    } else {
                        wrong_num_args = true;
                    }
                }
                Some(d) => {
                    is_agg = d.x_finalize;
                    if d.func_flags & SQLITE_FUNC_UNLIKELY != 0 {
                        p.em(e).flags |= EP_Unlikely;
                        if n == 2 {
                            let a1 = p.l(list).a[1].p_expr;
                            let prob = expr_probability(p, a1);
                            p.em(e).i_table = prob;
                            if prob < 0 {
                                let msg = format!(
                                    "second argument to {}() must be a constant between 0.0 and 1.0",
                                    p.e(e).tok()
                                );
                                p.error_msg_expr(msg, e);
                                p.ncm(nc).n_nc_err += 1;
                            }
                        } else {
                            // EVIDENCE-OF: R-61304-29449 The unlikely(X) function is
                            // equivalent to likelihood(X, 0.0625).
                            // EVIDENCE-OF: R-01283-11636 The unlikely(X) function is
                            // short-hand for likelihood(X,0.0625).
                            // EVIDENCE-OF: R-36850-34127 The likely(X) function is
                            // short-hand for likelihood(X,0.9375).
                            // EVIDENCE-OF: R-53436-40973 The likely(X) function is
                            // equivalent to likelihood(X,0.9375).
                            // TUNING: unlikely() probability is 0.0625. likely() is 0.9375
                            p.em(e).i_table = if d.name.as_bytes()[0] == b'u' { 8388608 } else { 125829120 };
                        }
                    }
                    // (sqlite3AuthCheck(pParse, SQLITE_FUNCTION, ...): the engine authorizes)

                    // If the function may call sqlite3_value_subtype(), then set the
                    // EP_SubtArg flag on all of its argument expressions. This prevents
                    // where.c from replacing the expressions with correlated
                    // sub-expressions from an expression index.
                    if (d.func_flags & SQLITE_SUBTYPE as u32) != 0 || p.e(e).has(EP_SubtArg) {
                        resolve_set_expr_subtype_arg(p, list);
                    }
                    if d.func_flags & (SQLITE_FUNC_CONSTANT | SQLITE_FUNC_SLOCHNG) != 0 {
                        // For the purposes of the EP_ConstFunc flag, date and time functions
                        // and other functions that change slowly are considered constant
                        // because they are constant for the duration of one query. This
                        // allows them to be factored out of inner loops.
                        p.em(e).flags |= EP_ConstFunc;
                    }
                    if (d.func_flags & SQLITE_FUNC_CONSTANT) == 0 {
                        // Clearly non-deterministic functions like random(), but also
                        // date/time functions that use 'now', and other functions like
                        // sqlite_version() that might change over time cannot be used in an
                        // index or generated column.
                        sqlite3_resolve_not_valid(
                            p,
                            nc,
                            "non-deterministic functions",
                            NC_IdxExpr | NC_PartIdx | NC_GenCol,
                            ExprId::NULL,
                            e,
                        );
                    } else {
                        // Must fit in 8 bits
                        let f = p.nc(nc).nc_flags & NC_SelfRef;
                        p.em(e).op2 = f as u8;
                    }
                    if (d.func_flags & SQLITE_FUNC_INTERNAL) != 0
                        && p.nested == 0
                        && (p.db.m_db_flags & DBFLAG_InternalFunc as u32) == 0
                    {
                        // Internal-use-only functions are disallowed unless the SQL is being
                        // compiled using sqlite3NestedParse() or the
                        // SQLITE_TESTCTRL_INTERNAL_FUNCTIONS test-control has be used to turn
                        // on access to such functions.
                        no_such_func = 2;
                        def = None;
                    } else if (d.func_flags & (SQLITE_FUNC_DIRECT | SQLITE_FUNC_UNSAFE)) != 0 && !p.in_rename_object() {
                        if p.nc(nc).nc_flags & NC_FromDDL != 0 {
                            p.em(e).flags |= EP_FromDDL;
                        }
                        sqlite3_expr_function_usable(p, e, &d);
                    }
                }
            }

            if !p.in_rename_object() {
                // (pWin: window functions are not ported in step V1; the parser reports a
                // statement with OVER / FILTER as unsupported, so pWin==0 here)
                let d_is_window = def.as_ref().is_some_and(|d| (d.func_flags & SQLITE_FUNC_WINDOW) != 0);
                if (is_agg && (p.nc(nc).nc_flags & NC_AllowAgg) == 0) || (is_agg && d_is_window) {
                    let z_type = if d_is_window { "window" } else { "aggregate" };
                    let msg = format!("misuse of {} function {}()", z_type, p.e(e).tok());
                    p.error_msg_expr(msg, e);
                    p.ncm(nc).n_nc_err += 1;
                    is_agg = false;
                } else if no_such_func != 0 && !p.db.init_busy {
                    let msg = format!("no such function: {}", p.e(e).tok());
                    p.error_msg_expr(msg, e);
                    p.ncm(nc).n_nc_err += 1;
                } else if wrong_num_args {
                    let msg = format!("wrong number of arguments to function {}()", p.e(e).tok());
                    p.error_msg_expr(msg, e);
                    p.ncm(nc).n_nc_err += 1;
                } else if !is_agg && p.e(e).has(EP_WinFunc) {
                    let msg = format!("FILTER may not be used with non-aggregate {}()", p.e(e).tok());
                    p.error_msg_expr(msg, e);
                    p.ncm(nc).n_nc_err += 1;
                } else if !is_agg && p.e(e).p_left.nn() {
                    sqlite3_expr_order_by_aggregate_error(p, e);
                    p.ncm(nc).n_nc_err += 1;
                }
                if is_agg {
                    // Window functions may not be arguments of aggregate functions. Or
                    // arguments of other window functions. But aggregate functions may be
                    // arguments for window functions.
                    p.ncm(nc).nc_flags &= !(NC_AllowWin | NC_AllowAgg);
                }
            } else if p.e(e).has(EP_WinFunc) || p.e(e).p_left.nn() {
                is_agg = true;
            }
            sqlite3_walk_expr_list(p, w, list);
            if is_agg {
                let left = p.e(e).p_left;
                if left.nn() {
                    let l = p.e(left).x_list();
                    sqlite3_walk_expr_list(p, w, l);
                }
                {
                    // For looping up thru outer contexts
                    p.em(e).op = TK_AGG_FUNCTION;
                    p.em(e).op2 = 0;
                    if p.e(e).has(EP_WinFunc) {
                        let f = p.a_win[p.e(e).y_win.ix()].p_filter;
                        sqlite3_walk_expr(p, w, f);
                    }
                    let mut nc2 = nc;
                    while nc2.nn() && {
                        let sl = p.nc(nc2).p_src_list;
                        sqlite3_references_src_list(p, e, sl) == 0
                    } {
                        let add = 1 + p.nc(nc2).n_nested_select;
                        p.em(e).op2 = (p.e(e).op2 as u32 + add) as u8;
                        nc2 = p.nc(nc2).p_next;
                    }
                    if nc2.nn()
                        && let Some(d) = def.as_ref()
                    {
                        let add = p.nc(nc2).n_nested_select;
                        p.em(e).op2 = (p.e(e).op2 as u32 + add) as u8;
                        // NC_MinMaxAgg==SQLITE_FUNC_MINMAX and NC_OrderAgg==SQLITE_FUNC_ANYORDER
                        let f = (d.func_flags ^ SQLITE_FUNC_ANYORDER) & (SQLITE_FUNC_MINMAX | SQLITE_FUNC_ANYORDER);
                        p.ncm(nc2).nc_flags |= NC_HasAgg | f as i32;
                    }
                }
                p.ncm(nc).nc_flags |= saved_allow_flags;
            }
            // FIX ME:  Compute pExpr->affinity based on the expected return type of the
            // function
            return WRC_Prune;
        }
        TK_EXISTS | TK_SELECT | TK_IN => {
            if p.e(e).use_x_select() {
                let n_ref = p.nc(nc).n_ref;
                if p.e(e).op == TK_EXISTS {
                    p.b_has_exists = true;
                }
                if p.nc(nc).nc_flags & NC_SelfRef != 0 {
                    not_valid_impl(p, nc, "subqueries", e, e);
                } else {
                    let s = p.e(e).x_select();
                    sqlite3_walk_select(p, w, s);
                }
                if n_ref != p.nc(nc).n_ref {
                    p.em(e).flags |= EP_VarSelect;
                    let s = p.e(e).x_select();
                    p.sm(s).sel_flags |= SF_Correlated;
                }
                p.ncm(nc).nc_flags |= NC_Subquery;
            }
        }
        TK_VARIABLE => {
            sqlite3_resolve_not_valid(p, nc, "parameters", NC_IsCheck | NC_PartIdx | NC_IdxExpr | NC_GenCol, e, e);
        }
        TK_IS | TK_ISNOT => {
            let right = sqlite3_expr_skip_collate_and_likely(p, p.e(e).p_right);
            // Handle special cases of "x IS TRUE", "x IS FALSE", "x IS NOT TRUE", and
            // "x IS NOT FALSE".
            if right.nn() && (p.e(right).op == TK_ID || p.e(right).op == TK_TRUEFALSE) {
                let rc = resolve_expr_step(p, w, right);
                if rc == WRC_Abort {
                    return WRC_Abort;
                }
                if p.e(right).op == TK_TRUEFALSE {
                    let x = p.em(e);
                    x.op2 = x.op;
                    x.op = TK_TRUTH;
                    return WRC_Continue;
                }
            }
            comparison = true;
        }
        TK_BETWEEN | TK_EQ | TK_NE | TK_LT | TK_LE | TK_GT | TK_GE => comparison = true,
        _ => {}
    }
    if comparison {
        let n_left = sqlite3_expr_vector_size(p, p.e(e).p_left);
        let n_right;
        if p.e(e).op == TK_BETWEEN {
            let l = p.e(e).x_list();
            let mut r = sqlite3_expr_vector_size(p, p.l(l).a[0].p_expr);
            if r == n_left {
                r = sqlite3_expr_vector_size(p, p.l(l).a[1].p_expr);
            }
            n_right = r;
        } else {
            n_right = sqlite3_expr_vector_size(p, p.e(e).p_right);
        }
        if n_left != n_right {
            p.error_msg("row value misused");
            p.record_error_offset_of_expr(e);
        }
    }
    if p.n_err != 0 { WRC_Abort } else { WRC_Continue }
}

/// `resolveAsName(pParse, pEList, pE)`: `e` is an expression which is a single term of an
/// ORDER BY or GROUP BY clause. If it is an identifier that matches one of the column names
/// (AS aliases) in `e_list`, return the 1-based index of that column; otherwise 0.
fn resolve_as_name(p: &Parse, e_list: ExprListId, e: ExprId) -> i32 {
    if p.e(e).op == TK_ID {
        let z_col = p.e(e).tok();
        for (i, it) in p.l(e_list).a.iter().enumerate() {
            if it.e_e_name == ENAME_NAME as u8 && it.z_e_name.as_deref().is_some_and(|z| z.eq_ignore_ascii_case(z_col)) {
                return i as i32 + 1;
            }
        }
    }
    0
}

/// `resolveOrderByTermToExprList(pParse, pSelect, pE)`: `e` is a single term of the ORDER BY
/// clause of a compound select. Attempt to match it against the result set columns of
/// `select`: return the 1-based index of the matching column, or 0 if there is none. Errors
/// during the resolution are suppressed (`db->suppressErr`).
fn resolve_order_by_term_to_expr_list(p: &mut Parse, select: SelectId, e: ExprId) -> i32 {
    let e_list = p.s(select).p_e_list;
    // Resolve all names in the ORDER BY term expression
    let nc = p.new_nc(NameContext {
        p_src_list: p.s(select).p_src,
        p_e_list: e_list,
        nc_flags: NC_AllowAgg | NC_UEList | NC_NoSelect,
        n_nc_err: 0,
        ..NameContext::default()
    });
    let saved_supp_err = p.suppress_err;
    p.suppress_err = true;
    let rc = sqlite3_resolve_expr_names(p, nc, e);
    p.suppress_err = saved_supp_err;
    p.a_nc.truncate(nc.ix());
    if rc != 0 {
        return 0;
    }
    // Try to match the ORDER BY expression against an expression in the result set. Return
    // an 1-based index of the matching result-set entry.
    for i in 0..p.l(e_list).a.len() {
        if sqlite3_expr_compare(p, false, p.l(e_list).a[i].p_expr, e, -1) < 2 {
            return i as i32 + 1;
        }
    }
    // If no match, return 0.
    0
}

/// The ordinal of an integer for `%r` in error messages ("1st", "2nd", "3rd", "4th", …).
fn ordinal(i: i32) -> String {
    let x = i.abs();
    let mut ix = (x % 10) as usize;
    if ix >= 4 || (x / 10) % 10 == 1 {
        ix = 0;
    }
    const Z_ORD: [&str; 4] = ["th", "st", "nd", "rd"];
    format!("{}{}", i, Z_ORD[ix])
}

/// `resolveOutOfRangeError(pParse, zType, i, mx, pError)`: generate an ORDER BY or GROUP BY
/// term out-of-range error.
fn resolve_out_of_range_error(p: &mut Parse, z_type: &str, i: i32, mx: i32, error: ExprId) {
    p.error_msg(format!(
        "{} {} BY term out of range - should be between 1 and {}",
        ordinal(i),
        z_type,
        mx
    ));
    p.record_error_offset_of_expr(error);
}

/// `resolveCompoundOrderBy(pParse, pSelect)`: analyze the ORDER BY clause in a compound
/// SELECT statement. Modify each term of the ORDER BY clause that is a constant integer
/// between 1 and N (the number of result columns) or matches a result-set column or alias
/// into the integer column number, recording it in `iOrderByCol`. Return the number of
/// errors seen.
fn resolve_compound_order_by(p: &mut Parse, select: SelectId) -> i32 {
    let order_by = p.s(select).p_order_by;
    if order_by.is_null() {
        return 0;
    }
    if p.l(order_by).n_expr() > p.db.a_limit[SQLITE_LIMIT_COLUMN as usize] {
        p.error_msg("too many terms in ORDER BY clause");
        return 1;
    }
    for it in p.lm(order_by).a.iter_mut() {
        it.done = false;
    }
    let mut select = select;
    p.sm(select).p_next = SelectId::NULL;
    while p.s(select).p_prior.nn() {
        let prior = p.s(select).p_prior;
        p.sm(prior).p_next = select;
        select = prior;
    }
    let mut more_to_do = true;
    while select.nn() && more_to_do {
        more_to_do = false;
        let e_list = p.s(select).p_e_list;
        for i in 0..p.l(order_by).a.len() {
            if p.l(order_by).a[i].done {
                continue;
            }
            let item_expr = p.l(order_by).a[i].p_expr;
            let pe = sqlite3_expr_skip_collate_and_likely(p, item_expr);
            if pe.is_null() {
                continue;
            }
            let mut i_col;
            if let Some(v) = sqlite3_expr_is_integer(p, pe, false, false) {
                i_col = v;
                if i_col <= 0 || i_col > p.l(e_list).n_expr() {
                    let n = p.l(e_list).n_expr();
                    resolve_out_of_range_error(p, "ORDER", i as i32 + 1, n, pe);
                    return 1;
                }
            } else {
                i_col = resolve_as_name(p, e_list, pe);
                if i_col == 0 {
                    // Now test if expression pE matches one of the values returned by
                    // pSelect. In the usual case this is done by duplicating the expression,
                    // resolving any symbols in it, and then comparing it against each
                    // expression returned by the SELECT statement. Once the comparisons are
                    // finished, the duplicate expression is discarded.
                    let dup = sqlite3_expr_dup(p, pe, 0);
                    i_col = resolve_order_by_term_to_expr_list(p, select, dup);
                    if p.unsupported.is_some() {
                        return 1;
                    }
                }
            }
            if i_col > 0 {
                // Convert the ORDER BY term into an integer column number iCol, taking care
                // to preserve the COLLATE clause if it exists.
                let new = sqlite3_expr_int32(p, i_col);
                if item_expr == pe {
                    p.lm(order_by).a[i].p_expr = new;
                } else {
                    let mut parent = item_expr;
                    while p.e(p.e(parent).p_left).op == TK_COLLATE {
                        parent = p.e(parent).p_left;
                    }
                    p.em(parent).p_left = new;
                }
                p.lm(order_by).a[i].i_order_by_col = i_col as u16;
                p.lm(order_by).a[i].done = true;
            } else {
                more_to_do = true;
            }
        }
        select = p.s(select).p_next;
    }
    for i in 0..p.l(order_by).a.len() {
        if !p.l(order_by).a[i].done {
            p.error_msg(format!(
                "{} ORDER BY term does not match any column in the result set",
                ordinal(i as i32 + 1)
            ));
            return 1;
        }
    }
    0
}

/// `sqlite3ResolveOrderGroupBy(pParse, pSelect, pOrderBy, zType)`: check every term in the
/// ORDER BY or GROUP BY clause `order_by` of `select`. If any term refers to a result set
/// expression (as determined by the `iOrderByCol` field) then convert that term into a copy
/// of the corresponding result set column.
///
/// If any errors are detected, add an error message to the Parse and return non-zero.
pub fn sqlite3_resolve_order_group_by(p: &mut Parse, select: SelectId, order_by: ExprListId, z_type: &str) -> i32 {
    if order_by.is_null() || p.in_rename_object() {
        return 0;
    }
    if p.l(order_by).n_expr() > p.db.a_limit[SQLITE_LIMIT_COLUMN as usize] {
        p.error_msg(format!("too many terms in {z_type} BY clause"));
        return 1;
    }
    let e_list = p.s(select).p_e_list;
    for i in 0..p.l(order_by).a.len() {
        let (col, item_expr) = {
            let it = &p.l(order_by).a[i];
            (it.i_order_by_col as i32, it.p_expr)
        };
        if col != 0 {
            if col > p.l(e_list).n_expr() {
                let n = p.l(e_list).n_expr();
                resolve_out_of_range_error(p, z_type, i as i32 + 1, n, ExprId::NULL);
                return 1;
            }
            resolve_alias(p, e_list, col - 1, item_expr, 0);
        }
    }
    0
}

/// `resolveOrderGroupBy(pNC, pSelect, pOrderBy, zType)`: `order_by` is an ORDER BY or GROUP
/// BY clause in SELECT statement `select`. The name context of the SELECT statement is `nc`.
/// `z_type` is either "ORDER" or "GROUP" depending on which type of clause `order_by` holds.
///
/// This routine resolves each term of the clause into an expression. If the order-by term
/// is an integer I between 1 and N (where N is the number of columns in the result set of
/// the SELECT) then the expression in the resolution is a copy of the I-th result-set
/// expression. If the order-by term is an identifier that corresponds to the AS-name of a
/// result-set expression, then the term resolves to a copy of the result-set expression.
/// Otherwise, the expression is resolved in the usual way - using sqlite3ResolveExprNames().
///
/// This routine returns the number of errors. If errors occur, then an appropriate error
/// message might be left in the Parse. (OOM errors excepted.)
fn resolve_order_group_by(p: &mut Parse, nc: NcId, select: SelectId, order_by: ExprListId, z_type: &str) -> i32 {
    let n_result = p.l(p.s(select).p_e_list).n_expr();
    for i in 0..p.l(order_by).a.len() {
        let pe = p.l(order_by).a[i].p_expr;
        let pe2 = sqlite3_expr_skip_collate_and_likely(p, pe);
        if pe2.is_null() {
            continue;
        }
        if z_type.as_bytes()[0] != b'G' {
            let i_col = resolve_as_name(p, p.s(select).p_e_list, pe2);
            if i_col > 0 {
                // If an AS-name match is found, mark this ORDER BY column as being a copy of
                // the iCol-th result-set column. The subsequent call to
                // sqlite3ResolveOrderGroupBy() will convert the expression to a copy of the
                // iCol-th result-set expression.
                p.lm(order_by).a[i].i_order_by_col = i_col as u16;
                continue;
            }
        }
        if let Some(i_col) = sqlite3_expr_is_integer(p, pe2, false, false) {
            // The ORDER BY term is an integer constant. Again, set the column number so that
            // sqlite3ResolveOrderGroupBy() will convert the order-by term to a copy of the
            // result-set expression
            if !(1..=0xffff).contains(&i_col) {
                resolve_out_of_range_error(p, z_type, i as i32 + 1, n_result, pe2);
                return 1;
            }
            p.lm(order_by).a[i].i_order_by_col = i_col as u16;
            continue;
        }

        // Otherwise, treat the ORDER BY term as an ordinary expression
        p.lm(order_by).a[i].i_order_by_col = 0;
        if sqlite3_resolve_expr_names(p, nc, pe) != 0 {
            return 1;
        }
        let e_list = p.s(select).p_e_list;
        for j in 0..p.l(e_list).a.len() {
            if sqlite3_expr_compare(p, false, pe, p.l(e_list).a[j].p_expr, -1) == 0 {
                // Since this expression is being changed into a reference to an identical
                // expression in the result set, remove all Window objects belonging to the
                // expression from the Select.pWin list. (window functions: not ported)
                p.lm(order_by).a[i].i_order_by_col = j as u16 + 1;
            }
        }
    }
    sqlite3_resolve_order_group_by(p, select, order_by, z_type)
}

/// `resolveSelectStep(pWalker, p)`: resolve names in the SELECT statement `sel` and all of
/// its descendants.
fn resolve_select_step(p: &mut Parse, w: &mut Walker, sel: SelectId) -> i32 {
    if p.s(sel).sel_flags & SF_Resolved != 0 {
        return WRC_Prune;
    }
    let outer_nc = w.p_nc;

    // Normally sqlite3SelectExpand() will be called first and will have already expanded
    // this SELECT. However, if this is a subquery within an expression, sqlite3ResolveExprNames()
    // will be called without a prior call to sqlite3SelectExpand(). When that happens, let
    // sqlite3SelectPrep() do all of the processing for this SELECT. sqlite3SelectPrep() will
    // invoke both sqlite3SelectExpand() and this routine in the correct order.
    if (p.s(sel).sel_flags & SF_Expanded) == 0 {
        sqlite3_select_prep(p, sel, outer_nc);
        return if p.n_err != 0 { WRC_Abort } else { WRC_Prune };
    }

    let is_compound = p.s(sel).p_prior.nn() as i32;
    let mut n_compound = 0;
    let leftmost = sel;
    let mut s = sel;
    let nc_mark = p.a_nc.len();
    while s.nn() {
        p.sm(s).sel_flags |= SF_Resolved;

        // Resolve the expressions in the LIMIT and OFFSET clauses. These are not allowed to
        // refer to any names, so pass an empty NameContext.
        let snc = p.new_nc(NameContext { p_win_select: s, ..NameContext::default() });
        let lim = p.s(s).p_limit;
        if sqlite3_resolve_expr_names(p, snc, lim) != 0 {
            p.a_nc.truncate(nc_mark);
            return WRC_Abort;
        }

        // If the SF_Converted flags is set, then this Select object was created by the
        // convertCompoundSelectToSubquery() function (not ported in step V1).

        // Recursively resolve names in all subqueries in the FROM clause
        if outer_nc.nn() {
            p.ncm(outer_nc).n_nested_select += 1;
        }
        let src = p.s(s).p_src;
        for i in 0..p.src(src).a.len() {
            let sub = {
                let it = &p.src(src).a[i];
                if it.is_subquery { it.p_subq.as_ref().map(|q| q.p_select) } else { None }
            };
            if let Some(sub) = sub
                && (p.s(sub).sel_flags & SF_Resolved) == 0
            {
                let n_ref = if outer_nc.nn() { p.nc(outer_nc).n_ref } else { 0 };
                sqlite3_resolve_select_names(p, sub, outer_nc);
                if p.n_err != 0 {
                    p.a_nc.truncate(nc_mark);
                    return WRC_Abort;
                }
                // If the number of references to the outer context changed when expressions
                // in the sub-select were resolved, the sub-select is correlated. It is not
                // required to check the ref-count increased, as the above checks nRef>=nRef.
                if outer_nc.nn() {
                    p.srcm(src).a[i].is_correlated = p.nc(outer_nc).n_ref > n_ref;
                }
            }
        }
        if outer_nc.nn() && p.nc(outer_nc).n_nested_select > 0 {
            p.ncm(outer_nc).n_nested_select -= 1;
        }

        // Set up the local name-context to pass to sqlite3ResolveExprNames() to resolve the
        // result-set expression list.
        {
            let n = p.ncm(snc);
            n.nc_flags = NC_AllowAgg | NC_AllowWin;
            n.p_src_list = src;
            n.p_next = outer_nc;
        }

        // Resolve names in the result set.
        let e_list = p.s(s).p_e_list;
        if sqlite3_resolve_expr_list_names(p, snc, e_list) != 0 {
            p.a_nc.truncate(nc_mark);
            return WRC_Abort;
        }
        p.ncm(snc).nc_flags &= !NC_AllowWin;

        // If there are no aggregate functions in the result-set, and no GROUP BY expression,
        // do not allow aggregates in any of the other expressions.
        let group_by = p.s(s).p_group_by;
        if group_by.nn() || (p.nc(snc).nc_flags & NC_HasAgg) != 0 {
            // NC_MinMaxAgg==SF_MinMaxAgg, NC_OrderAgg==SF_OrderByReqd
            let f = (p.nc(snc).nc_flags & (NC_MinMaxAgg | NC_OrderAgg)) as u32;
            p.sm(s).sel_flags |= SF_Aggregate | f;
        } else {
            p.ncm(snc).nc_flags &= !NC_AllowAgg;
        }

        // Add the output column list to the name-context before parsing the other
        // expressions in the SELECT statement. This is so that expressions in the WHERE
        // clause (etc.) can refer to expressions by aliases in the result set.
        //
        // Minor point: If this is the case, then the expression will be re-evaluated for
        // each reference to it.
        p.ncm(snc).p_e_list = e_list;
        p.ncm(snc).nc_flags |= NC_UEList;
        if p.s(s).p_having.nn() {
            if (p.s(s).sel_flags & SF_Aggregate) == 0 {
                p.error_msg("HAVING clause on a non-aggregate query");
                p.a_nc.truncate(nc_mark);
                return WRC_Abort;
            }
            let h = p.s(s).p_having;
            if sqlite3_resolve_expr_names(p, snc, h) != 0 {
                p.a_nc.truncate(nc_mark);
                return WRC_Abort;
            }
        }
        p.ncm(snc).nc_flags |= NC_Where;
        let wh = p.s(s).p_where;
        if sqlite3_resolve_expr_names(p, snc, wh) != 0 {
            p.a_nc.truncate(nc_mark);
            return WRC_Abort;
        }
        p.ncm(snc).nc_flags &= !NC_Where;

        // Resolve names in table-valued-function arguments
        for i in 0..p.src(src).a.len() {
            let (is_tab_func, arg) = {
                let it = &p.src(src).a[i];
                (it.is_tab_func, it.p_func_arg)
            };
            if is_tab_func && sqlite3_resolve_expr_list_names(p, snc, arg) != 0 {
                p.a_nc.truncate(nc_mark);
                return WRC_Abort;
            }
        }

        // The ORDER BY and GROUP BY clauses may not refer to terms in outer queries
        p.ncm(snc).p_next = NcId::NULL;
        p.ncm(snc).nc_flags |= NC_AllowAgg | NC_AllowWin;

        // Process the ORDER BY clause for singleton SELECT statements. The ORDER BY clause
        // for compounds SELECT statements is handled below, after all of the result-sets for
        // all of the elements of the compound have been resolved.
        //
        // If there is an ORDER BY clause on a term of a compound-select other than the
        // right-most term, then that is a syntax error. But the error is not detected until
        // much later, and so we need to go ahead and resolve those symbols on the incorrect
        // ORDER BY for consistency.
        let ob = p.s(s).p_order_by;
        if ob.nn() && is_compound <= n_compound && resolve_order_group_by(p, snc, s, ob, "ORDER") != 0 {
            p.a_nc.truncate(nc_mark);
            return WRC_Abort;
        }
        p.ncm(snc).nc_flags &= !NC_AllowWin;

        // Resolve the GROUP BY clause. At the same time, make sure the GROUP BY clause does
        // not contain aggregate functions.
        if group_by.nn() {
            if resolve_order_group_by(p, snc, s, group_by, "GROUP") != 0 {
                p.a_nc.truncate(nc_mark);
                return WRC_Abort;
            }
            for i in 0..p.l(group_by).a.len() {
                if p.e(p.l(group_by).a[i].p_expr).has(EP_Agg) {
                    p.error_msg("aggregate functions are not allowed in the GROUP BY clause");
                    p.a_nc.truncate(nc_mark);
                    return WRC_Abort;
                }
            }
        }

        // If this is part of a compound SELECT, check that it has the right number of
        // expressions in the select list.
        let next = p.s(s).p_next;
        if next.nn() && p.l(p.s(s).p_e_list).n_expr() != p.l(p.s(next).p_e_list).n_expr() {
            sqlite3_select_wrong_num_terms_error(p, next);
            p.a_nc.truncate(nc_mark);
            return WRC_Abort;
        }
        // If the SELECT statement contains ON clauses that were moved into the WHERE clause,
        // go through and verify that none of the terms in the ON clauses reference tables to
        // the right of the ON clause.
        if p.s(s).sel_flags & SF_OnToWhere != 0 {
            crate::flatten::sqlite3_select_check_on_clauses(p, s);
            if p.n_err != 0 {
                p.a_nc.truncate(nc_mark);
                return WRC_Abort;
            }
        }

        // Advance to the next term of the compound
        p.a_nc.truncate(nc_mark);
        s = p.s(s).p_prior;
        n_compound += 1;
    }

    // Resolve the ORDER BY on a compound SELECT after all terms of the compound have been
    // resolved.
    if is_compound != 0 && resolve_compound_order_by(p, leftmost) != 0 {
        return WRC_Abort;
    }
    WRC_Prune
}

/// `sqlite3ResolveExprNames(pNC, pExpr)`: this routine walks an expression tree and resolves
/// references to table columns and result-set columns. At the same time, do error checking
/// on function usage and set a flag if any aggregate functions are seen.
///
/// To resolve table columns references we look for nodes (or subtrees) of the form X.Y.Z or
/// Y.Z or just Z where X is the name of a database "main" or "temp" or the symbolic name
/// assigned to an ATTACH-ed database, Y is the name of a table, Z is the name of a column or
/// the ROWID of that table. The node type is converted from TK_ID / TK_DOT to TK_COLUMN.
///
/// Function calls are checked to make sure that the function is defined and that the correct
/// number of arguments are specified. If the function is an aggregate function, then the
/// NC_HasAgg flag is set and the opcode is changed from TK_FUNCTION to TK_AGG_FUNCTION. If
/// an expression contains aggregate functions then the EP_Agg property is set on the
/// expression.
///
/// An error message is left in the Parse if anything is amiss. The number of errors is
/// returned.
pub fn sqlite3_resolve_expr_names(p: &mut Parse, nc: NcId, e: ExprId) -> i32 {
    if e.is_null() {
        return SQLITE_OK;
    }
    let saved_has_agg = p.nc(nc).nc_flags & (NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
    p.ncm(nc).nc_flags &= !(NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
    let mut w = Walker {
        x_expr_callback: Some(resolve_expr_step),
        x_select_callback: if p.nc(nc).nc_flags & NC_NoSelect != 0 { None } else { Some(resolve_select_step) },
        x_select_callback2: None,
        p_nc: nc,
        ..Walker::default()
    };
    let h = p.e(e).n_height;
    p.n_height += h;
    let nh = p.n_height;
    if sqlite3_expr_check_height(p, nh) != 0 {
        return SQLITE_ERROR;
    }
    sqlite3_walk_expr_nn(p, &mut w, e);
    p.n_height -= h;
    let f = (p.nc(nc).nc_flags & (NC_HasAgg | NC_HasWin)) as u32;
    // EP_Agg==NC_HasAgg, EP_Win==NC_HasWin
    p.em(e).flags |= f;
    p.ncm(nc).nc_flags |= saved_has_agg;
    (p.nc(nc).n_nc_err > 0 || p.n_err > 0) as i32
}

/// `sqlite3ResolveExprListNames(pNC, pList)`: resolve all names for all expression in an
/// expression list. This is just a convenience routine that implements a loop around
/// sqlite3ResolveExprNames().
pub fn sqlite3_resolve_expr_list_names(p: &mut Parse, nc: NcId, list: ExprListId) -> i32 {
    if list.is_null() {
        return SQLITE_OK;
    }
    let mut w = Walker {
        x_expr_callback: Some(resolve_expr_step),
        x_select_callback: Some(resolve_select_step),
        x_select_callback2: None,
        p_nc: nc,
        ..Walker::default()
    };
    let mut saved_has_agg = p.nc(nc).nc_flags & (NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
    p.ncm(nc).nc_flags &= !(NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
    for i in 0..p.l(list).a.len() {
        let e = p.l(list).a[i].p_expr;
        if e.is_null() {
            continue;
        }
        let h = p.e(e).n_height;
        p.n_height += h;
        let nh = p.n_height;
        if sqlite3_expr_check_height(p, nh) != 0 {
            return SQLITE_ERROR;
        }
        sqlite3_walk_expr_nn(p, &mut w, e);
        p.n_height -= h;
        if p.nc(nc).nc_flags & (NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg) != 0 {
            let f = (p.nc(nc).nc_flags & (NC_HasAgg | NC_HasWin)) as u32;
            // (the list item may have been replaced by resolveAlias: re-read it)
            let e = p.l(list).a[i].p_expr;
            p.em(e).flags |= f;
            saved_has_agg |= p.nc(nc).nc_flags & (NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
            p.ncm(nc).nc_flags &= !(NC_HasAgg | NC_MinMaxAgg | NC_HasWin | NC_OrderAgg);
        }
        if p.n_err > 0 {
            return SQLITE_ERROR;
        }
    }
    p.ncm(nc).nc_flags |= saved_has_agg;
    SQLITE_OK
}

/// `sqlite3ResolveSelectNames(pParse, p, pOuterNC)`: resolve all names in all expressions of
/// a SELECT and in all descendants of the SELECT, including compounds off of p->pPrior,
/// subqueries in expressions, and subqueries used as FROM clause terms.
///
/// See sqlite3ResolveExprNames() for a description of the kinds of transformations that
/// occur.
///
/// All SELECT statements should have been expanded using sqlite3SelectExpand() prior to
/// invoking this routine.
pub fn sqlite3_resolve_select_names(p: &mut Parse, sel: SelectId, outer_nc: NcId) {
    let mut w = Walker {
        x_expr_callback: Some(resolve_expr_step),
        x_select_callback: Some(resolve_select_step),
        x_select_callback2: None,
        p_nc: outer_nc,
        ..Walker::default()
    };
    sqlite3_walk_select(p, &mut w, sel);
}

#[allow(dead_code)]
fn _unused(p: &mut Parse) {
    // keep `is_quote` reachable for later steps (schema-name comparisons use it)
    let _ = is_quote(b'"');
    let _ = sqlite3_get_coll_seq(p, "BINARY");
}

/// `sqlite3ResolveSelfReference(pParse, pTab, type, pExpr, pList)`: resolve names in
/// expressions that can only reference a single table or not reference any tables at all:
///
///    "type" flag         Expression type
///    ------------        -----------------------------
///    NC_IsCheck          CHECK constraints
///    NC_PartIdx          WHERE clause of a partial index
///    NC_IdxExpr          Index expressions
///    NC_GenCol           Expression for a generated column
///
/// The Expr.iTable value for Expr.op==TK_COLUMN nodes of the expression is set to -1 and the
/// Expr.iColumn value is set to the column number.
///
/// Any errors cause an error message to be set in pParse.
pub fn sqlite3_resolve_self_reference(p: &mut Parse, tab: TableId, mut ty: i32, e: ExprId, list: ExprListId) -> i32 {
    let mut src = SrcList::default();
    if tab.nn() {
        src.a.push(SrcItem { z_name: Some(p.tab(tab).z_name.clone()), p_s_tab: tab, i_cursor: -1, ..SrcItem::default() });
        if p.tab(tab).i_db != 1 {
            // Cause EP_FromDDL to be set on TK_FUNCTION nodes of non-TEMP schema elements
            ty |= NC_FromDDL;
        }
    }
    let src = p.new_src(src);
    let mark = p.a_nc.len();
    let nc = p.new_nc(NameContext { p_src_list: src, nc_flags: ty | NC_IsDDL, ..NameContext::default() });
    let mut rc = sqlite3_resolve_expr_names(p, nc, e);
    if rc == SQLITE_OK && list.nn() {
        rc = sqlite3_resolve_expr_list_names(p, nc, list);
    }
    p.a_nc.truncate(mark);
    rc
}
